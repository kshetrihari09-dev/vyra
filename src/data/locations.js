/* Nepal administrative divisions for address and shop-location fields: all 7 provinces, 77 districts and 753 local levels
   (municipalities / rural municipalities), each with its number of wards where known. Generated by
   backend/scripts/build_nepal_locations.py from open data (MIT) — don't edit nepalLocations.json by hand.
   Ids that existed before the full dataset (e.g. "butwal-sub", "ktm-metro") are unchanged, so saved addresses still resolve. */
import data from "./nepalLocations.json" with { type: "json" };

export const PROVINCES = data.provinces;
export const DISTRICTS = data.districts;
export const MUNICIPALITIES = data.municipalities;

export const districtsFor = (provinceId) => DISTRICTS[provinceId] || [];
export const municipalitiesFor = (districtId) => MUNICIPALITIES[districtId] || [];
export const provinceName = (id) => PROVINCES.find((p) => p.id === id)?.name || "";
export const districtName = (provinceId, id) => districtsFor(provinceId).find((d) => d.id === id)?.name || "";
export const municipalityName = (districtId, id) => municipalitiesFor(districtId).find((m) => m.id === id)?.name || "";

/** Number of wards in a municipality, or null when the source doesn't say (a few municipalities in the Nawalparasi and Rukum districts). */
export const wardCountFor = (districtId, municipalityId) => municipalitiesFor(districtId).find((m) => m.id === municipalityId)?.wards ?? null;
export const wardOptions = (districtId, municipalityId) => Array.from({ length: wardCountFor(districtId, municipalityId) || 0 }, (_, i) => String(i + 1));
